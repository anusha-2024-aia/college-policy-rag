import React, { useState } from 'react';
import {
  Sparkles,
  ListChecks,
  FileCheck2,
  AlertTriangle,
  BookOpen,
  ChevronUp,
  ChevronDown,
  ExternalLink,
  ShieldAlert,
  FileText,
  CheckCircle2,
} from 'lucide-react';
import MarkdownRenderer from './MarkdownRenderer';
import { formatRoleName } from '../utils/roles';

/**
 * Intelligent section partitioner:
 * Separates policy answers into:
 * 1. Answer Summary (core synthesis / primary finding)
 * 2. Key Rules & Conditions (specific requirements, lists, caveats, criteria)
 */
function partitionAnswerSections(answerText) {
  if (!answerText) return { summary: '', rules: '', remainder: '' };

  // Common section divider headings generated by models or standard policies
  const dividerRegex = /(?:^|\n)(?:###?\s*(?:Important Rules|Rules & Conditions|Key Requirements|Provisions|Conditions|Requirements|Policies|Procedures|Exceptions|Details|Guidelines|Criteria)[^\n]*)/i;

  const match = answerText.match(dividerRegex);
  if (match) {
    const splitIndex = match.index;
    const summary = answerText.substring(0, splitIndex).trim();
    const rules = answerText.substring(splitIndex).trim();
    return { summary, rules, hasDedicatedRulesSection: true };
  }

  // If no explicit heading, check if text has bullet points or numbered lists
  const listStartIndex = answerText.search(/(?:^|\n)\s*([*+-]|\d+\.)\s+/);
  if (listStartIndex !== -1) {
    const summary = answerText.substring(0, listStartIndex).trim();
    const rules = answerText.substring(listStartIndex).trim();
    if (summary.length > 0) {
      return { summary, rules, hasDedicatedRulesSection: true };
    }
  }

  // If it's a multi-paragraph answer, treat first paragraph as summary and remainder as details
  const paragraphs = answerText.split(/\n\s*\n/).filter((p) => p.trim());
  if (paragraphs.length > 1) {
    const summary = paragraphs[0].trim();
    const rules = paragraphs.slice(1).join('\n\n').trim();
    return { summary, rules, hasDedicatedRulesSection: false };
  }

  return { summary: answerText.trim(), rules: '', hasDedicatedRulesSection: false };
}

export default function PolicyAnswerView({
  result,
  userRole,
  onInspectDocument,
  onCitationClick,
}) {
  const [citationsExpanded, setCitationsExpanded] = useState(true);
  const [activeCitationIndex, setActiveCitationIndex] = useState(null);

  if (!result) return null;

  const currentRoleDisplay = formatRoleName(userRole);
  const { summary, rules, hasDedicatedRulesSection } = partitionAnswerSections(result.answer);

  // Group authoritative policies ONLY from cited passages (Bug 6 requirement)
  const activePoliciesMap = new Map();
  if (result.citations && result.citations.length > 0) {
    const passageByFilename = new Map();
    if (result.passages && result.passages.length > 0) {
      result.passages.forEach((p) => {
        if (!passageByFilename.has(p.file_name)) {
          passageByFilename.set(p.file_name, p);
        }
      });
    }

    result.citations.forEach((c) => {
      const p = passageByFilename.get(c.file_name);
      if (!activePoliciesMap.has(c.file_name)) {
        activePoliciesMap.set(c.file_name, {
          file_name: c.file_name,
          title: (p && p.document_title) || c.document_title || c.file_name.replace('.pdf', '').replace(/_/g, ' '),
          effective_date: (p && p.effective_date) || 'Active',
          is_superseded: p ? p.is_superseded : false,
          is_partially_amended: p ? p.is_partially_amended : false,
          amendment_scope: p ? p.amendment_scope : null,
          pages: new Set([c.page_number]),
        });
      } else {
        activePoliciesMap.get(c.file_name).pages.add(c.page_number);
      }
    });
  }

  const activePoliciesList = Array.from(activePoliciesMap.values());

  const handleCitationBadgeClick = (citNum) => {
    setActiveCitationIndex(citNum);
    setCitationsExpanded(true);
    const element = document.getElementById(`citation-card-${citNum}`);
    if (element) {
      element.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
      element.classList.add('citation-highlight');
      setTimeout(() => element.classList.remove('citation-highlight'), 2500);
    }
    if (onCitationClick) onCitationClick(citNum);
  };

  return (
    <div className="policy-answer-structured-container" id="policy-answer-view">
      {/* 1. Policy Version Conflict Warning (if applicable) */}
      {result.has_policy_conflict && (
        <div className="conflict-warning-card" role="alert" aria-live="polite">
          <div className="conflict-card-header">
            <AlertTriangle size={22} className="conflict-icon" />
            <div>
              <h4 className="conflict-title">Policy Version Conflict Detected</h4>
              <p className="conflict-subtitle">
                The retrieved evidence contains provisions from both an active policy and a superseded predecessor. The synthesized answer adheres strictly to the <strong>active authoritative policy</strong>.
              </p>
            </div>
          </div>

          {result.conflict_details && result.conflict_details.length > 0 && (
            <div className="conflict-details-grid">
              {result.conflict_details.map((conf, cidx) => (
                <div key={cidx} className="conflict-item-card">
                  <div className="conflict-row active-policy-row">
                    <span className="policy-state-badge badge-active">Active Policy</span>
                    <strong>{conf.current_title}</strong>
                    <span className="policy-file-badge">{conf.current_file}</span>
                    <span className="policy-date-badge">Effective: {conf.current_effective_date}</span>
                  </div>
                  <div className="conflict-row superseded-policy-row">
                    <span className="policy-state-badge badge-superseded">Superseded</span>
                    <strong>{conf.superseded_title}</strong>
                    <span className="policy-file-badge">{conf.superseded_file}</span>
                    <span className="policy-date-badge">Effective: {conf.superseded_effective_date}</span>
                  </div>
                  {conf.description && (
                    <div className="conflict-resolution-note">
                      <strong>Resolution Note:</strong> {conf.description}
                    </div>
                  )}
                </div>
              ))}
            </div>
          )}
        </div>
      )}

      {/* 2. Structured Component: Answer Summary */}
      <div className="structured-section-card answer-summary-card">
        <div className="structured-section-header">
          <div className="section-title-wrapper">
            <div className="section-icon-badge summary-badge">
              <Sparkles size={18} />
            </div>
            <div>
              <h4 className="section-title">Answer Summary</h4>
              <span className="section-subtitle">
                Grounded institutional policy synthesis
              </span>
            </div>
          </div>

          <div className="section-header-badges">
            <span className="badge badge-success">
              <CheckCircle2 size={13} style={{ marginRight: '4px' }} />
              Authoritative Synthesis
            </span>
          </div>
        </div>

        <div className="structured-card-body summary-body">
          <MarkdownRenderer
            content={summary}
            onCitationClick={handleCitationBadgeClick}
            className="summary-markdown"
          />
        </div>
      </div>

      {/* 3. Structured Component: Important Rules and Conditions */}
      {rules && (
        <div className="structured-section-card rules-conditions-card">
          <div className="structured-section-header">
            <div className="section-title-wrapper">
              <div className="section-icon-badge rules-badge">
                <ListChecks size={18} />
              </div>
              <div>
                <h4 className="section-title">
                  {hasDedicatedRulesSection ? 'Important Rules & Conditions' : 'Detailed Policy Provisions'}
                </h4>
                <span className="section-subtitle">
                  Specific requirements, eligibility criteria, and procedural regulations
                </span>
              </div>
            </div>
          </div>

          <div className="structured-card-body rules-body">
            <MarkdownRenderer
              content={rules}
              onCitationClick={handleCitationBadgeClick}
              className="rules-markdown"
            />
          </div>
        </div>
      )}

      {/* 4. Structured Component: Active Policy Information */}
      {activePoliciesList.length > 0 && (
        <div className="structured-section-card active-policy-info-card">
          <div className="structured-section-header">
            <div className="section-title-wrapper">
              <div className="section-icon-badge policy-badge">
                <FileCheck2 size={18} />
              </div>
              <div>
                <h4 className="section-title">Active Policy Information</h4>
                <span className="section-subtitle">
                  Institutional documents governing this response
                </span>
              </div>
            </div>
            <span className="badge badge-info">{activePoliciesList.length} Governing Document{activePoliciesList.length > 1 ? 's' : ''}</span>
          </div>

          <div className="active-policies-grid">
            {activePoliciesList.map((doc, didx) => (
              <div key={didx} className="active-policy-card">
                <div className="active-policy-header">
                  <div className="policy-doc-title">
                    <FileText size={16} className="doc-icon" />
                    <strong>{doc.title}</strong>
                  </div>
                  <span className={`badge ${doc.is_superseded ? 'badge-warning' : 'badge-success'}`}>
                    {doc.is_superseded ? 'Superseded' : doc.is_partially_amended ? 'Partially Amended' : 'Active & In Effect'}
                  </span>
                </div>

                <div className="active-policy-meta">
                  <span className="doc-filename">{doc.file_name}</span>
                  <span className="meta-separator">•</span>
                  <span>Effective: <strong>{doc.effective_date}</strong></span>
                  <span className="meta-separator">•</span>
                  <span>Pages cited: <strong>{Array.from(doc.pages).sort((a,b)=>a-b).join(', ')}</strong></span>
                </div>

                {doc.is_partially_amended && doc.amendment_scope && (
                  <div className="amendment-notice">
                    📌 <strong>Partial Amendment Scope:</strong> {doc.amendment_scope}
                  </div>
                )}
              </div>
            ))}
          </div>
        </div>
      )}

      {/* 5. Structured Component: Citation Cards with Evidence Excerpts */}
      {result.citations && result.citations.length > 0 && (
        <div className="citations-container" id="citations-section">
          <button
            className="citations-header-btn"
            onClick={() => setCitationsExpanded(!citationsExpanded)}
            aria-expanded={citationsExpanded}
            type="button"
          >
            <div style={{ display: 'flex', alignItems: 'center', gap: '0.65rem' }}>
              <BookOpen size={18} color="var(--brand-blue)" />
              <span style={{ fontWeight: 700, fontSize: '1rem', color: 'var(--text-primary)' }}>
                Verified Evidence Citations ({result.citations.length})
              </span>
            </div>
            <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
              <span style={{ fontSize: '0.78rem', color: 'var(--text-muted)' }}>
                {citationsExpanded ? 'Collapse' : 'Expand'}
              </span>
              {citationsExpanded ? <ChevronUp size={18} /> : <ChevronDown size={18} />}
            </div>
          </button>

          {citationsExpanded && (
            <div className="citation-cards-list">
              {result.citations.map((cit, cidx) => {
                const citNumber = cit.index || cidx + 1;
                const isHighlighted = activeCitationIndex === citNumber;

                // Find corresponding passage for full title / date
                const matchingPassage = result.passages?.find((p) => p.index === citNumber || p.file_name === cit.file_name);
                const docTitle = matchingPassage?.document_title || cit.file_name.replace('.pdf', '').replace(/_/g, ' ');

                return (
                  <div
                    key={cidx}
                    id={`citation-card-${citNumber}`}
                    className={`citation-card ${isHighlighted ? 'citation-active-border' : ''}`}
                  >
                    <div className="citation-meta">
                      <div className="citation-title">
                        <span className="citation-index-badge">[{citNumber}]</span>
                        <div className="citation-doc-info">
                          <strong className="citation-doc-name">{docTitle}</strong>
                          <span className="citation-doc-filename">{cit.file_name}</span>
                        </div>
                      </div>

                      <div className="citation-actions">
                        <span className="badge badge-neutral citation-page-badge">
                          Page {cit.page_number}
                        </span>

                        <button
                          className="btn btn-secondary btn-sm citation-inspect-btn"
                          onClick={() => onInspectDocument && onInspectDocument(cit, matchingPassage)}
                          title={`Inspect complete metadata for ${cit.file_name}`}
                          type="button"
                        >
                          <ExternalLink size={13} />
                          <span>Inspect</span>
                        </button>
                      </div>
                    </div>

                    {cit.snippet && (
                      <div className="citation-snippet">
                        <span className="snippet-quote-mark">“</span>
                        {cit.snippet}
                        <span className="snippet-quote-mark">”</span>
                      </div>
                    )}
                  </div>
                );
              })}
            </div>
          )}
        </div>
      )}

      {/* 6. Structured Component: Institutional Compliance Advisory */}
      <div className="institutional-advisory-card" role="note">
        <div className="advisory-icon-wrapper">
          <ShieldAlert size={20} />
        </div>
        <div className="advisory-content">
          <strong>Official Institutional Compliance Advisory:</strong>
          <p>
            Responses are generated strictly from indexed institutional policies for the <strong>{currentRoleDisplay}</strong> demo permission level. This system upholds evidentiary verification and prevents speculative answers. For binding official rulings, exceptions, or formal administrative petitions, please contact the Office of the Registrar or Dean of Academic Affairs.
          </p>
        </div>
      </div>
    </div>
  );
}
